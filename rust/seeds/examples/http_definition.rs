//! Author an independent log.http Definition; no existing registered RX changes.
use data_seeds::{Field, doc};
fn main() -> Result<(), Box<dyn std::error::Error>> {
    let output = std::env::args().nth(1).ok_or("output RX path required")?;
    let definition = doc::new("http")
        .namespace("log")
        .version(1, 0)
        .field(
            Field::new("time")
                .r#type("uint")
                .size(6)
                .annotation("@time")
                .annotation("@otel(Timestamp)"),
        )
        .field(Field::new("id").r#type("bytes").size(10).annotation("@log"))
        .field(
            Field::new("leaf_id")
                .r#type("uint")
                .size(2)
                .annotation("@leaf"),
        )
        .field(
            Field::new("observed_time")
                .r#type("uint")
                .size(6)
                .annotation("@unit(ms)")
                .annotation("@otel(ObservedTimestamp)"),
        )
        .field(
            Field::new("level")
                .r#type("uint")
                .size(1)
                .annotation("@otel(SeverityNumber)"),
        )
        .field(
            Field::new("level_text")
                .r#type("tstr")
                .annotation("@otel(SeverityText)"),
        )
        .field(
            Field::new("message")
                .r#type("any")
                .annotation("@otel(Body)"),
        )
        .field(
            Field::new("trace_id")
                .r#type("bytes")
                .size(16)
                .annotation("@otel(TraceId)"),
        )
        .field(
            Field::new("span_id")
                .r#type("bytes")
                .size(8)
                .annotation("@otel(SpanId)"),
        )
        .field(
            Field::new("trace_flags")
                .r#type("uint")
                .size(1)
                .annotation("@otel(TraceFlags)"),
        )
        .field(
            Field::new("method")
                .r#type("tstr")
                .annotation("@otel(http.request.method)"),
        )
        .field(
            Field::new("route")
                .r#type("tstr")
                .annotation("@otel(http.route)"),
        )
        .field(
            Field::new("status")
                .r#type("uint")
                .size(2)
                .annotation("@otel(http.response.status_code)"),
        )
        .field(
            Field::new("duration")
                .r#type("uint")
                .size(4)
                .annotation("@unit(us)")
                .annotation("#summ(numeric)"),
        )
        .field(
            Field::new("attributes")
                .array("any")
                .annotation("@fields")
                .annotation("@otel(Attributes)"),
        )
        .sign()?;
    definition.write(output)?;
    Ok(())
}
