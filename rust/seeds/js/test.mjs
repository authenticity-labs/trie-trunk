import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createSeeds } from './seeds.mjs';
const [wasm,dir]=process.argv.slice(2);
const runtime=await createSeeds(await readFile(wasm));
const definition=runtime.prescribe(await readFile(`${dir}/sample.rx`));
const packBytes=await readFile(`${dir}/sample.pac`);
const pack=definition.open(packBytes);
assert.deepEqual(pack.info(),{length:10000,byteLength:packBytes.byteLength,sealed:true,hour:null});
const packs=runtime.packs().pack(pack);
pack.dispose();definition.dispose();
const q=packs.query().filter('reading','>=',990).select('sequence','reading','note').orderBy('sequence','desc').limit(10);
const batch=q.fetch(100);
assert.equal(batch.length,10);
const views=batch.views(),objects=batch.objects();
assert.deepEqual(views.map(v=>({...v})),objects);
assert.ok(objects.every(o=>o.reading>=990));
assert.ok(objects.every((o,i)=>i===0||o.sequence<objects[i-1].sequence));
assert.equal(q.fetch(1).length,0);
q.dispose();packs.dispose();
assert.equal(views[0].sequence,objects[0].sequence);
assert.ok(batch.retainedBytes>0);
assert.throws(()=>{views[0].reading=1;},TypeError);
batch.dispose();assert.throws(()=>views[0].sequence,/Released/);
const d=runtime.prescribe(await readFile(`${dir}/sample.rx`));const p=d.open(await readFile(`${dir}/sample.pac`));
const s=runtime.beds().pack(p);const all=s.query().limit(3).objects();
const compressed=d.open(await readFile(`${dir}/sample.zstd.pac`));
const compressedStore=runtime.packs().pack(compressed);assert.equal(compressedStore.query().limit(1).objects()[0].sequence,0);compressedStore.dispose();compressed.dispose();
const box=runtime.packs(await readFile(`${dir}/sample.box`),[d]);
assert.equal(box.query().orderBy('sequence','desc').limit(1).objects()[0].sequence,9999);box.dispose();
assert.equal(all[0].note,null);assert.equal('note' in all[2],false);
assert.equal(all[0].extra[0].large,18446744073709551615n);
assert.equal(all[0].extra[0].__proto__,'safe');assert.equal(Object.getPrototypeOf(all[0].extra[0]),Object.prototype);
assert.throws(()=>s.query().select('typo').fetch(),/unknown query field/);
const cancel=s.query();const first=cancel.fetch(1);first.dispose();cancel.cancel();assert.throws(()=>cancel.fetch(1),/cancelled/);
cancel.dispose();s.dispose();p.dispose();d.dispose();
console.log('WASM filtering, global top-k, view/object parity, lifetime, absent/null, bigint, prototype safety, and cancellation passed');

const streamDefinition=runtime.prescribe(await readFile(`${dir}/sample.rx`));
const frame=await readFile(`${dir}/sample.zstd.pac`);
const receive=streamDefinition.receive(frame.length),streamStore=runtime.beds();
streamDefinition.dispose(); // The Rust receiver retains its registration.
const stream=Buffer.concat([frame,frame]);
let at=0,received=0;
for(const end of [1,3,31,frame.length+3,stream.length]) {
  const packs=receive.load(stream.subarray(at,end));at=end;
  for(const pack of packs){assert.equal(pack.info().sealed,true);assert.equal(pack.info().length,10000);streamStore.pack(pack);pack.dispose();received++;}
  assert.equal(received,Math.floor(end/frame.length));
}
assert.equal(receive.finish(),2);
assert.throws(()=>receive.load(new Uint8Array()),/finished/);
receive.dispose();
const streamed=streamStore.query().select('sequence').orderBy('sequence','desc').limit(4).objects();
assert.deepEqual(streamed.map(v=>v.sequence),[9999,9999,9998,9998]);
streamStore.dispose();
const truncatedDefinition=runtime.prescribe(await readFile(`${dir}/sample.rx`));
const truncated=truncatedDefinition.receive(frame.length);
assert.deepEqual(truncated.load(frame.subarray(0,frame.length-1)),[]);
assert.throws(()=>truncated.finish(),/Truncated/);
truncated.dispose();truncatedDefinition.dispose();
console.log('Rust streaming receive, fragmented headers, incremental delivery, truncation and shared lifetimes passed');
const summaryBytes=await readFile(`${dir}/sample.summ`);
const summaries=runtime.summaries(summaryBytes,1,2);
const summaryQuery=summaries.query().filter('f1.max','>',990).select('count','f1.max');
const summaryBatch=summaryQuery.fetch(288),summaryViews=summaryBatch.views(),summaryObjects=summaryBatch.objects();
assert.ok(summaryObjects.length>0);
assert.deepEqual(summaryViews.map(v=>({...v})),summaryObjects);
assert.ok(summaryObjects.every(v=>v.count>0&&v['f1.max']>990));
summaryQuery.dispose();summaries.dispose();
assert.equal(summaryViews[0].count,summaryObjects[0].count);
summaryBatch.dispose();
const emptySummaries=runtime.summaries(summaryBytes,0,1),emptyQuery=emptySummaries.query().filter('count','>',0);
assert.deepEqual(emptyQuery.objects(),[]);emptyQuery.dispose();emptySummaries.dispose();
assert.throws(()=>runtime.summaries(summaryBytes,0,3),/outside the Box/);
console.log('Fixed summary Box selection, Rust filtering, view/object parity and shared owner lifetime passed');
